export const reviewWord = (n: number) => {
  const t = n % 10, h = n % 100
  if (t === 1 && h !== 11) return 'отзыв'
  if (t >= 2 && t <= 4 && (h < 12 || h > 14)) return 'отзыва'
  return 'отзывов'
}

